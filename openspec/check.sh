#!/usr/bin/env bash
# OpenSpec checks (openspec/specs/openspec-tooling). Run from anywhere inside the repository:
#   bash openspec/check.sh
# Uses the global `openspec` when its version equals openspec/cli.pin, otherwise the pinned
# package through `npm exec`. OPENSPEC overrides the command.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

pin=$(tr -d '[:space:]' < openspec/cli.pin)
[[ -n $pin ]] || { echo "FAIL: openspec/cli.pin is empty"; exit 1; }
export OPENSPEC_TELEMETRY=0

if [[ -n ${OPENSPEC:-} ]]; then
  read -r -a cli <<< "$OPENSPEC"
elif command -v openspec >/dev/null && [[ $(openspec --version 2>/dev/null) == "$pin" ]]; then
  cli=(openspec)
else
  cli=(npm exec --yes --package="@fission-ai/openspec@$pin" -- openspec)
fi

version=$("${cli[@]}" --version)
[[ $version == "$pin" ]] || { echo "FAIL: openspec $version runs, the pin is $pin"; exit 1; }

failed=0
fail() { echo "FAIL: $*"; failed=1; }

# 1. Strict validation of the main specs and the active changes.
"${cli[@]}" validate --all --strict --no-interactive || fail "openspec validate --all --strict"

# 2. No main spec keeps the placeholder Purpose left by archiving.
for spec in openspec/specs/*/spec.md; do
  [[ -e $spec ]] || continue
  purpose=$(awk '/^## Purpose/{p=1; next} /^## /{p=0} p && NF {print; exit}' "$spec")
  [[ $purpose == "TBD - created by archiving change"* ]] && fail "$spec: Purpose is the archive placeholder"
done

# 3. Every active change was created by `openspec new change`.
for change in openspec/changes/*/; do
  [[ -d $change && $(basename "$change") != archive ]] || continue
  [[ -f $change.openspec.yaml ]] || fail "${change%/}: no .openspec.yaml (create changes with \`openspec new change\`)"
done

# 4. The skills were generated by the pinned CLI.
skills=0
for skill in .claude/skills/openspec-*/SKILL.md .agents/skills/openspec-*/SKILL.md; do
  [[ -e $skill ]] || continue
  skills=$((skills + 1))
  generated=$(sed -n 's/^ *generatedBy: *"\{0,1\}\([^"]*\)"\{0,1\} *$/\1/p' "$skill" | head -n 1)
  [[ $generated == "$pin" ]] || fail "$skill: generatedBy '${generated}', the pin is $pin"
done
(( skills > 0 )) || fail "no OpenSpec skills in .claude/skills or .agents/skills"

# 5. No archived change leaves an agent task open; open [human] tasks are allowed.
while IFS= read -r hit; do
  fail "open task in an archived change: $hit"
done < <(grep -nH -E '^[[:space:]]*- \[ \]' openspec/changes/archive/*/tasks.md 2>/dev/null | grep -v -F '[human]' || true)

(( failed == 0 )) || exit 1
echo ok
